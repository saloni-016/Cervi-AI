"""One-time Neon setup; run privately in Cloud Shell, not in GitHub Actions."""

import re
import secrets
import sys
from getpass import getpass
from urllib.parse import quote

import psycopg
from psycopg.conninfo import conninfo_to_dict
from psycopg.sql import Identifier, Literal, SQL


ROLE = "cerviai_app"
TLS = {"sslmode": "verify-full", "sslrootcert": "system", "channel_binding": "require"}
NEON_HOST = re.compile(r"ep-[a-z0-9-]+\.[a-z0-9.-]+\.neon\.tech")


class SetupError(ValueError):
    pass


def owner_settings(uri):
    try:
        config = conninfo_to_dict(uri)
    except psycopg.Error:
        raise SetupError("Paste the raw owner postgresql:// URL, not the psql command.") from None
    host = config.get("host", "")
    if (
        not uri.startswith("postgresql://") or not NEON_HOST.fullmatch(host)
        or host.split(".", 1)[0].endswith("-pooler") or config.get("port", "5432") != "5432"
        or not all(config.get(key) for key in ("dbname", "user", "password"))
    ):
        raise SetupError("Use the direct Neon owner connection URL (turn Connection pooling off).")
    return {key: config[key] for key in ("host", "dbname", "user", "password")}


def provision(conn, password):
    """Provision only the two tables and a non-owner login. Caller commits or rolls back."""
    exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (ROLE,)).fetchone()
    if exists:
        raise SetupError("The app role already exists. Reuse its saved URL; nothing was changed.")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS public.users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT, email TEXT UNIQUE, password TEXT
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS public.results (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT, risk_level TEXT, probability DOUBLE PRECISION, created_at TEXT
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS cerviai_results_email ON public.results (email, id DESC)")
    # Send a SCRAM verifier, not the plaintext password, in the role DDL.
    verifier = conn.pgconn.encrypt_password(password.encode(), ROLE.encode(), b"scram-sha-256").decode()
    role = Identifier(ROLE)
    conn.execute(SQL("CREATE ROLE {} LOGIN PASSWORD {}").format(role, Literal(verifier)))
    database = conn.execute("SELECT current_database()").fetchone()[0]
    conn.execute(SQL("GRANT CONNECT ON DATABASE {} TO {}").format(Identifier(database), role))
    conn.execute(SQL("GRANT USAGE ON SCHEMA public TO {}").format(role))
    conn.execute(SQL("GRANT SELECT, INSERT ON public.users, public.results TO {}").format(role))


def pooled_url(settings, password):
    endpoint, domain = settings["host"].split(".", 1)
    return (f"postgresql://{ROLE}:{quote(password, safe='')}@{endpoint}-pooler.{domain}/"
            f"{quote(settings['dbname'], safe='')}?sslmode=verify-full&channel_binding=require")


def main():
    if not sys.stdin.isatty():
        sys.exit("Run this script interactively in a private Cloud Shell terminal.")
    try:
        config = owner_settings(getpass("Paste the direct Neon owner URL (hidden): "))
        print(f"This will create CerviAI tables and a limited login in {config['dbname']} at {config['host']}.")
        if input("Type YES to continue: ") != "YES":
            print("Cancelled. No database changes.")
            return
        password = secrets.token_urlsafe(32)
        with psycopg.connect(**config, **TLS, connect_timeout=15) as conn:
            provision(conn, password)
    except SetupError as exc:
        sys.exit(f"Neon setup: {exc}")
    except psycopg.Error as exc:
        sys.exit(f"Neon setup failed ({exc.sqlstate or 'connection error'}). Check the owner URL, branch and permissions.")
    print("Save the following app-only URL in a password manager for Step 4. Do not share it.")
    print(pooled_url(config, password))


if __name__ == "__main__":
    main()
